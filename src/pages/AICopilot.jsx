import React, { useState } from 'react';
import { useApp } from '../context/AppContext';
import { calculateMetrics, generateRecommendations } from '../store/dataStore';
import { Bot, Sparkles, ChevronRight, AlertCircle, MessageSquare } from 'lucide-react';

const QUESTIONS = [
  { id: 'next100', label: 'How can I get the next 100 registrations?' },
  { id: 'channel', label: 'Which channel should I prioritize?' },
  { id: 'referral', label: 'How can I improve referrals?' },
  { id: 'budget', label: 'How should I spend the remaining budget?' },
  { id: 'today', label: 'What should I do today?' },
  { id: 'target', label: 'How far am I from the 500-registration target?' },
];

function renderMarkdown(text) {
  return text
    .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
    .replace(/^(\d+️⃣|[🎯📊📣⏱️💡🔗✉️🏆🔄💰⛔✅📱🚨⚠️📍📅])\s/gm, '<br/><span style="margin-right:4px">$1</span>');
}

export default function AICopilot() {
  const { data } = useApp();
  const metrics = calculateMetrics(data);
  const [activeQ, setActiveQ] = useState(null);
  const [response, setResponse] = useState(null);
  const [loading, setLoading] = useState(false);

  const handleQuestion = (qId) => {
    setActiveQ(qId);
    setLoading(true);
    // Simulate slight delay for UX
    setTimeout(() => {
      const rec = generateRecommendations(metrics, qId);
      setResponse(rec);
      setLoading(false);
    }, 600);
  };

  return (
    <div className="animate-fade-in">
      <div style={{ marginBottom: 28 }}>
        <h1 className="section-title">AI Growth Copilot</h1>
        <p className="section-subtitle">Rule-based local recommendation engine — no API key required, no external AI called</p>
      </div>

      <div style={{ background: 'rgba(245,158,11,0.05)', border: '1px solid rgba(245,158,11,0.15)', borderRadius: 8, padding: '12px 16px', marginBottom: 24, display: 'flex', alignItems: 'center', gap: 10 }}>
        <AlertCircle size={16} color="#f59e0b" />
        <span style={{ fontSize: 13, color: '#a0a0a0' }}>
          <strong style={{ color: '#f59e0b' }}>Transparency:</strong> Recommendations are generated by a local rule-based engine using your demo campaign metrics. No live AI model is called. Responses will differ from a real AI conversation.
        </span>
      </div>

      {/* Live Metrics Summary */}
      <div className="card-dark" style={{ padding: 20, marginBottom: 24 }}>
        <div style={{ fontSize: 13, fontWeight: 600, color: '#707070', marginBottom: 12, textTransform: 'uppercase', letterSpacing: '0.08em' }}>Current Campaign Snapshot</div>
        <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(160px, 1fr))', gap: 12 }}>
          {[
            { label: 'Registrations', value: `${metrics.totalReg} / 500` },
            { label: 'Days Remaining', value: metrics.daysRemaining },
            { label: 'Referral Rate', value: `${metrics.referralRate}%` },
            { label: 'Budget Remaining', value: `₹${metrics.budgetRemaining}` },
            { label: 'Campaign Health', value: metrics.healthLabel },
            { label: 'Progress', value: `${metrics.progressPct}%` },
          ].map(m => (
            <div key={m.label} style={{ background: '#0a0a0a', border: '1px solid #1e1e1e', borderRadius: 8, padding: '10px 14px' }}>
              <div style={{ fontSize: 11, color: '#505050', marginBottom: 4 }}>{m.label}</div>
              <div style={{ fontSize: 16, fontWeight: 700, color: '#f59e0b' }}>{m.value}</div>
            </div>
          ))}
        </div>
      </div>

      <div style={{ display: 'grid', gridTemplateColumns: '280px 1fr', gap: 24 }}>
        {/* Questions */}
        <div className="card-dark" style={{ padding: 16, height: 'fit-content' }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 16 }}>
            <MessageSquare size={16} color="#f59e0b" />
            <span style={{ fontSize: 14, fontWeight: 600, color: '#e8e8e8' }}>Ask a Question</span>
          </div>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 6 }}>
            {QUESTIONS.map(q => (
              <button
                key={q.id}
                onClick={() => handleQuestion(q.id)}
                style={{
                  background: activeQ === q.id ? 'rgba(245,158,11,0.12)' : 'transparent',
                  border: `1px solid ${activeQ === q.id ? 'rgba(245,158,11,0.3)' : '#1e1e1e'}`,
                  borderRadius: 8, padding: '10px 12px', cursor: 'pointer',
                  display: 'flex', justifyContent: 'space-between', alignItems: 'center',
                  color: activeQ === q.id ? '#f59e0b' : '#a0a0a0',
                  fontSize: 13, textAlign: 'left', transition: 'all 0.15s ease',
                }}
              >
                <span>{q.label}</span>
                <ChevronRight size={14} style={{ flexShrink: 0, opacity: 0.5 }} />
              </button>
            ))}
          </div>
        </div>

        {/* Response */}
        <div className="card-dark" style={{ padding: 24, minHeight: 300 }}>
          {loading ? (
            <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', height: '100%', gap: 16, minHeight: 250 }}>
              <div style={{ width: 48, height: 48, borderRadius: '50%', background: 'rgba(245,158,11,0.1)', border: '2px solid rgba(245,158,11,0.3)', display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
                <Bot size={22} color="#f59e0b" className="animate-pulse-gold" />
              </div>
              <div style={{ fontSize: 14, color: '#707070' }}>Analyzing campaign metrics...</div>
            </div>
          ) : response ? (
            <div className="animate-fade-in">
              <div style={{ display: 'flex', align: 'center', gap: 10, marginBottom: 20 }}>
                <div style={{ width: 40, height: 40, borderRadius: 10, background: 'rgba(245,158,11,0.1)', border: '1px solid rgba(245,158,11,0.2)', display: 'flex', alignItems: 'center', justifyContent: 'center', flexShrink: 0 }}>
                  <Bot size={20} color="#f59e0b" />
                </div>
                <div>
                  <div style={{ fontSize: 16, fontWeight: 700, color: '#e8e8e8' }}>{response.title}</div>
                  <div style={{ fontSize: 12, color: '#505050' }}>Based on your current demo metrics</div>
                </div>
              </div>

              <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
                {response.points.map((point, i) => (
                  <div key={i} style={{ background: '#0a0a0a', border: '1px solid #1e1e1e', borderRadius: 8, padding: '12px 16px' }}>
                    <p style={{ margin: 0, fontSize: 14, color: '#c8c8c8', lineHeight: 1.7 }}
                      dangerouslySetInnerHTML={{ __html: renderMarkdown(point) }} />
                  </div>
                ))}
              </div>

              <div style={{ marginTop: 20, padding: 12, background: 'rgba(245,158,11,0.05)', border: '1px solid rgba(245,158,11,0.1)', borderRadius: 8, fontSize: 11, color: '#505050' }}>
                <Sparkles size={11} color="#f59e0b" style={{ display: 'inline', marginRight: 4 }} />
                Generated by local rule engine · Based on {metrics.totalReg} demo registrations · {metrics.daysRemaining} campaign days remaining
              </div>
            </div>
          ) : (
            <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', height: '100%', gap: 16, minHeight: 250 }}>
              <div style={{ width: 64, height: 64, borderRadius: '50%', background: 'rgba(245,158,11,0.05)', border: '1px solid rgba(245,158,11,0.1)', display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
                <Bot size={28} color="#505050" />
              </div>
              <div style={{ textAlign: 'center' }}>
                <div style={{ fontSize: 15, fontWeight: 600, color: '#505050', marginBottom: 8 }}>Select a question to get started</div>
                <div style={{ fontSize: 13, color: '#303030' }}>Recommendations are based on your current demo metrics</div>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
